import uuid
from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class ScoreRequest(BaseModel):
  model_config = ConfigDict(
    json_schema_extra={
      "example": {
        "source_account": "acc_a1b2c3d4e5f6",
        "target_account": "acc_f6e5d4c3b2a1",
        "amount": 250000,
        "channel": "transfer",
        "device": "dev_0a1b2c3d4e",
      }
    }
  )

  transaction_id: uuid.UUID | None = Field(
    None, description="Optional id; generated by the API when omitted."
  )
  source_account: str = Field(description="Account that sends the money.")
  target_account: str = Field(description="Account that receives the money.")
  amount: float = Field(gt=0, description="Amount in COP.")
  channel: Literal["transfer", "qr", "bill_payment", "topup", "withdrawal"]
  device: str | None = Field(None, description="Device id of the app session.")
  created_at: datetime | None = Field(
    None, description="Transaction time; defaults to the time of the request."
  )
  meta: dict | None = Field(
    None, description="Simulation metadata (ground truth); ignored by scoring."
  )


class Reason(BaseModel):
  feature: str = Field(description="Model feature behind this reason.")
  text: str = Field(description="Plain-language explanation.")
  effect: str = Field(description="raises_risk or lowers_risk.")
  impact: float = Field(description="SHAP contribution to the score (log-odds).")


class ScoreResponse(BaseModel):
  decision_id: uuid.UUID
  transaction_id: uuid.UUID
  action: Literal["approve", "challenge", "hold"] = Field(
    description="approve: no friction; challenge: ask for OTP; hold: retain and alert an analyst."
  )
  score: float = Field(description="Fraud probability between 0 and 1.")
  reasons: list[Reason]
  latency_ms: float
  model_version: str
